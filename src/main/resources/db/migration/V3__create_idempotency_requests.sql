-- Used to prevent duplicate requests from the same user

CREATE TABLE idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    operation VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,

    request_hash VARCHAR(64) NOT NULL,

    response_status SMALLINT,
    response_body JSONB,
    response_location TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_idempotency_request UNIQUE (user_id, operation, idempotency_key),

    CONSTRAINT chk_idempotency_response_status
        CHECK (response_status IS NULL OR response_status BETWEEN 100 AND 599)
);

CREATE INDEX idx_idempotency_expires_at ON idempotency_requests(expires_at);
