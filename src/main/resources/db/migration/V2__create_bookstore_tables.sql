-- Add the rest of the tables
-- 'categories' was created in V1

-- USERS

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_user_role CHECK (role IN ('ADMIN', 'USER'))
);

-- BOOKS

-- allow overselling, but never set quantity to <0
-- 'cover_image_url' is the url of the image (could be stored in S3)
-- use NUMERIC stores decimal values exactly => best for monetary calculations (compared to DOUBLE, FLOAT)
-- 'archived_at' is used for when the bookstore admin 'deletes' a book
-- => instead of deleting it completely, it will be set to archived and will not be shown
-- if restored, the 'archived_at' will be set to NULL
-- purpose: keep order history

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    description TEXT,
    price NUMERIC(6, 2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    cover_image_url VARCHAR(2048),
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_book_price CHECK (price >= 0),
    CONSTRAINT chk_book_stock CHECK (stock >= 0)
);

-- BOOK CATEGORIES (Many-to-Many)

-- one book can have many categories
-- one category can have many books

CREATE TABLE book_categories (
    book_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    PRIMARY KEY (book_id, category_id),

    CONSTRAINT fk_book_categories_book FOREIGN KEY (book_id) REFERENCES books(id),
    CONSTRAINT fk_book_categories_category FOREIGN KEY (category_id) REFERENCES categories(id)
);

-- SHOPPING CARTS

-- one user can have only one cart => user_id is unique
-- a cart is created not on user creation, but when they add their first item ever
-- => lazy creation because a user may never add an item to the cart, thus we would create an entity that is never used
-- on placing an order the cart is cleared, not deleted (meaning that the cart_items for the cart are deleted)

CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users(id)
);

-- CART ITEMS

-- (cart item = cart + book) relation

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,

    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_book FOREIGN KEY (book_id) REFERENCES books(id),
    CONSTRAINT uq_cart_book UNIQUE (cart_id, book_id),
    CONSTRAINT chk_cart_item_quantity CHECK (quantity > 0)
);

-- ORDERS

-- an order is created based on a cart
-- requires at least one item in a cart (number of cart_items for the cart is not 0)
-- once an order is placed, the cart is cleared (meaning that the cart_items for the cart are deleted)
-- a user can have many orders

-- PENDING = Order accepted by the API, waiting for asynchronous processing.
-- PROCESSING = Kafka consumer is processing the order and checking inventory.
-- CONFIRMED = All requested books have been allocated or reserved
-- BACKORDERED = At least one requested book is awaiting stock
-- SHIPPED = All items in the order have been shipped
-- DELIVERED = The customer has received the order
-- CANCELLED = Order was cancelled and won't be fulfilled

-- possible status transition 1: PENDING -> PROCESSING -> CONFIRMED -> SHIPPED -> DELIVERED
-- possible status transition 2: PENDING -> PROCESSING -> BACKORDERED -> SHIPPED -> DELIVERED
-- possible status transition 3: PENDING/PROCESSING/BACKORDERED -> CANCELLED (CANCELLED is possible before SHIPPED)

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    total_amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT chk_order_status CHECK (status IN ('PENDING', 'PROCESSING', 'CONFIRMED', 'BACKORDERED', 'SHIPPED', 'DELIVERED','CANCELLED')),
    CONSTRAINT chk_order_total CHECK (total_amount >= 0)
);

-- ORDER ITEMS
-- unit_price is the price the customer bought the item at
-- the price may change after the order was placed => preserving a historical snapshot
-- the order_items are a copy of the cart_items

-- quantity is the total requested quantity
-- allocated_quantity is the purchased available quantity
-- backorder_quantity is the remaining quantity that is not available (in case of overselling)

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    allocated_quantity INTEGER NOT NULL DEFAULT 0,
    backordered_quantity INTEGER NOT NULL DEFAULT 0,
    unit_price NUMERIC(6, 2) NOT NULL,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_order_items_book FOREIGN KEY (book_id) REFERENCES books(id),
    CONSTRAINT uq_order_book UNIQUE (order_id, book_id),
    CONSTRAINT chk_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_allocated_quantity CHECK (allocated_quantity >= 0),
    CONSTRAINT chk_backordered_quantity CHECK (backordered_quantity >= 0),
    CONSTRAINT chk_order_item_allocation CHECK (allocated_quantity + backordered_quantity <= quantity),
    CONSTRAINT chk_order_item_price CHECK (unit_price >= 0)
);

-- INDEXES
CREATE INDEX idx_books_title ON books (title);
CREATE INDEX idx_books_author ON books (author);
CREATE INDEX idx_books_archived_at ON books (archived_at);
CREATE INDEX idx_book_categories_category ON book_categories (category_id);
CREATE INDEX idx_cart_items_book ON cart_items (book_id);
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_order_items_book ON order_items (book_id);
